import { AsyncLocalStorage } from "node:async_hooks";
import { randomUUID } from "node:crypto";

// Shared kernel and shared infrastructure (KR-BE-1-002 Sections 5.2 and 5.5): request-context types with no
// domain meaning, no framework import and no dependency on any module. Any module may use them.
//
// The context holds two separate identifiers. The request ID (KR-BE-1-005) identifies one request and is always
// generated by the server. The correlation ID (KR-BE-1-008, decisions/KR-BE-1-008-correlation-policy.md) lets a client
// or a gateway follow a flow across requests: it is a validated client value or, otherwise, a generated one. The
// authenticated principal and the tenant are added by later tasks, once the identity decisions exist.

export interface RequestContext {
  // Server-generated, opaque and unique. It never comes from the client and encodes no user data.
  readonly requestId: string;
  // A client X-Correlation-ID that passed validation, used exactly as sent, or a server-generated cor-<uuid>. It is a
  // diagnostic identifier only: never a credential, never part of a response body, never derived from request data.
  readonly correlationId: string;
}

export const REQUEST_ID_PATTERN = /^req-[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
export const GENERATED_CORRELATION_ID_PATTERN = /^cor-[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

// The accepted form of a client correlation identifier: 8 to 64 ASCII letters, digits, dot, underscore or hyphen.
// A fixed server policy, not a setting. The pattern has no multiline flag, so $ matches only the end of the value.
export const CLIENT_CORRELATION_ID_PATTERN = /^[A-Za-z0-9._-]{8,64}$/;

// The effective correlation ID for a request. A value that is not exactly one string in the accepted form (absent,
// empty, too short or long, other characters, or a header sent more than once, which arrives joined with a separator)
// is replaced by a generated identifier; the request is never rejected because of it.
export function resolveCorrelationId(clientValue: unknown): string {
  if (typeof clientValue === "string" && CLIENT_CORRELATION_ID_PATTERN.test(clientValue)) return clientValue;
  return `cor-${randomUUID()}`;
}

export class RequestContextMissingError extends Error {
  constructor() {
    super("No request context is active.");
    this.name = "RequestContextMissingError";
  }
}

const storage = new AsyncLocalStorage<RequestContext>();

export function createRequestContext(clientCorrelationId?: unknown): RequestContext {
  return Object.freeze({ requestId: `req-${randomUUID()}`, correlationId: resolveCorrelationId(clientCorrelationId) });
}

// Runs fn, and everything it starts asynchronously, with this context. Each request gets its own context, so
// concurrent requests never see each other's.
export function runWithRequestContext<T>(context: RequestContext, fn: () => T): T {
  return storage.run(context, fn);
}

export function currentRequestContext(): RequestContext | undefined {
  return storage.getStore();
}

export function requireRequestContext(): RequestContext {
  const context = storage.getStore();
  if (!context) throw new RequestContextMissingError();
  return context;
}
